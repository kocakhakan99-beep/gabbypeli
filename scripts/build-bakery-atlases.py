"""Pack the bakery source sets with transparent gutters (requires Pillow)."""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
BAKERY = ROOT / "assets/gabby/bakery"
OVEN_PARTS = ("oven_body", "oven_rack", "oven_glass", "oven_door_frame",
              "oven_handle", "temperature_knob")
GUTTER = 4
ROW_WIDTH = 1536


def read(path):
    return Image.open(path).convert("RGBA")


def frames_for(name):
    if name == "oven":
        return {part: read(BAKERY / f"{part}.webp") for part in OVEN_PARTS}
    frames = {path.stem: read(path) for path in sorted((BAKERY / "sets" / name).glob("*.webp"))
              if path.stem != "atlas"}
    if name == "wash":
        # Keep the delivered faucet in the library. The station uses a registered
        # housing and handle sequence. The pump head still slides behind its base.
        frames.pop("wash-spout")
        frames.pop("wash-lever")
        pump = frames.pop("wash-pump")
        width, height = pump.size
        frames["wash-pump-base"] = pump.crop((0, 60, width, height))
        frames["wash-pump-head"] = pump.crop((0, 0, width, 60))
    return frames


def pack(name):
    frames = frames_for(name)
    x = y = GUTTER
    row_height = used_width = 0
    rectangles = {}
    for key, frame in sorted(frames.items(), key=lambda item: (-item[1].height, item[0])):
        width, height = frame.size
        if x + width + GUTTER > ROW_WIDTH and x > GUTTER:
            x, y, row_height = GUTTER, y + row_height + GUTTER, 0
        rectangles[key] = (x, y, width, height)
        row_height = max(row_height, height)
        x += width + GUTTER
        used_width = max(used_width, x)
    sheet = Image.new("RGBA", (used_width, y + row_height + GUTTER))
    for key, (left, top, _, _) in rectangles.items():
        sheet.paste(frames[key], (left, top))
    directory = BAKERY / "sets" / name
    directory.mkdir(exist_ok=True)
    sheet.save(directory / "atlas.webp", lossless=True, method=6)
    (directory / "atlas.json").write_text(json.dumps({"frames": {
        key: {"frame": dict(zip(("x", "y", "w", "h"), box))}
        for key, box in sorted(rectangles.items())
    }}, indent=2) + "\n")
    return {
        "width": sheet.width,
        "height": sheet.height,
        "frames": {key: " ".join(map(str, box)) for key, box in sorted(rectangles.items())},
    }


if __name__ == "__main__":
    sets = {name: pack(name) for name in ("cookie", "cupcake", "bun", "tart", "wash", "oven")}
    (ROOT / "src/games/baking-atlas-frames.ts").write_text(
        "// Generated by scripts/build-bakery-atlases.py.\n"
        "type BakeryFrames = { width: number; height: number; frames: Record<string, string> };\n"
        "export const bakeryFrames: Record<string, BakeryFrames> = "
        + json.dumps(sets, indent=2) + ";\n"
    )
